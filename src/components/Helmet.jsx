/*
  Линейные рисунки шлемов (viewBox 120 x 140).
  Детали, которые лежат "сверху", закрашены классом solid —
  так линии задних деталей не просвечивают.
  Смотровые щели закрашены чёрным (класс dark).
*/
function Helmet({ type }) {
  if (type === 'great') {
    // топфхельм, вид спереди: плоский верх, крест из полос, щели и дыхальца
    return (
      <svg className="helmet__svg" viewBox="0 0 120 140" aria-hidden="true">
        <path className="solid" d="M32 32 Q32 20 60 19 Q88 20 88 32 L88 112 Q60 120 32 112 Z" />
        {/* шов верхней пластины */}
        <path d="M32 32 Q60 39 88 32" />
        {/* надбровная полоса */}
        <path d="M32 46 H88 M32 54 H88" />
        {/* вертикальная полоса */}
        <path d="M56 54 V115.5 M64 54 V115.5" />
        {/* смотровые щели */}
        <path className="dark" d="M37 57 H54 V62 H37 Z" />
        <path className="dark" d="M66 57 H83 V62 H66 Z" />
        {/* заклёпки */}
        {[40, 48, 72, 80].map((x) => (
          <circle key={x} className="rivet" cx={x} cy="50" r="1" />
        ))}
        {[74, 90, 106].map((y) => (
          <circle key={y} className="rivet" cx="60" cy={y} r="1" />
        ))}
        {/* дыхальца крестом по обе стороны */}
        {[44, 76].map((x) =>
          [
            [0, -7],
            [-5, 0],
            [0, 0],
            [5, 0],
            [0, 7],
          ].map(([dx, dy]) => <circle key={x + '-' + dx + '-' + dy} cx={x + dx} cy={88 + dy} r="1.5" />)
        )}
      </svg>
    )
  }

  if (type === 'kettle') {
    // шапель (железная шляпа), вид спереди: купол из четырёх долей и широкие поля
    return (
      <svg className="helmet__svg" viewBox="0 0 120 140" aria-hidden="true">
        {/* поля */}
        <path className="solid" d="M30 74 Q60 82 90 74 L112 94 Q60 106 8 94 Z" />
        <path d="M15 92 Q60 102 105 92" />
        {/* купол */}
        <path className="solid" d="M30 74 C30 44 42 26 60 26 C78 26 90 44 90 74 Q60 82 30 74 Z" />
        {/* швы между долями и гребень */}
        <path d="M60 26 V78 M60 26 Q46 42 45 77 M60 26 Q74 42 75 77" />
        {/* обод с заклёпками */}
        <path d="M30 66 Q60 74 90 66" />
        {[
          [36, 71.4],
          [52, 73.7],
          [68, 73.7],
          [84, 71.4],
        ].map(([x, y]) => (
          <circle key={x} className="rivet" cx={x} cy={y} r="1.3" />
        ))}
      </svg>
    )
  }

  if (type === 'sallet') {
    // немецкий салад с бевором, вид сбоку (смотрит вправо)
    return (
      <svg className="helmet__svg" viewBox="0 0 120 140" aria-hidden="true">
        {/* бевор закрывает подбородок и горло */}
        <path className="solid" d="M64 70 L104 68 Q110 92 100 108 Q86 122 70 114 Q62 94 64 70 Z" />
        <path d="M67 96 Q86 101 107 92" />
        {/* купол с длинным хвостом */}
        <path
          className="solid"
          d="M104 76 C106 42 88 20 60 20 C36 20 26 40 26 60 C24 76 14 88 4 96 C24 98 38 90 46 80 Z"
        />
        {/* смотровая щель прорезана прямо в куполе и выходит на передний край */}
        <path className="dark" d="M101.9 53 L72 53 L72 57 L102.9 57" />
        {[44, 58, 72, 86].map((x) => (
          <circle key={x} className="rivet" cx={x} cy={x < 50 ? 74 : 75} r="1.3" />
        ))}
      </svg>
    )
  }

  // барбют, вид спереди: высокий купол с гребнем и Т-образный вырез для лица
  return (
    <svg className="helmet__svg" viewBox="0 0 120 140" aria-hidden="true">
      <path className="solid" d="M60 14 C82 14 96 32 96 58 C96 80 92 98 94 118 Q60 128 26 118 C28 98 24 80 24 58 C24 32 38 14 60 14 Z" />
      {/* гребень по центру купола */}
      <path d="M60 15 V49" />
      {/* отогнутый край вокруг выреза */}
      <path d="M49.5 123 L49.5 73 Q45 69 30 69 L30 53 Q60 46 90 53 L90 69 Q75 69 70.5 73 L70.5 123" />
      {/* сам вырез */}
      <path className="dark" d="M34 56 Q60 50 86 56 L86 66 Q72 66 67 70 L67 124 L53 124 L53 70 Q48 66 34 66 Z" />
      {/* заклёпки подкладки */}
      {[
        [32, 38],
        [88, 38],
        [33, 110],
        [87, 110],
      ].map(([x, y]) => (
        <circle key={x + '-' + y} className="rivet" cx={x} cy={y} r="1.3" />
      ))}
    </svg>
  )
}

export default Helmet
